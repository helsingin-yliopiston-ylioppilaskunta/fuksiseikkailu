import * as React from 'react'
import { useQuery } from '@tanstack/react-query'
import { Link } from '@tanstack/react-router'
import {
    AlertCircle,
    Check,
    ChevronDown,
    ChevronUp,
    Edit3,
    MapPin,
    RefreshCw,
    Search,
} from 'lucide-react'

import { listCheckpointsOptions } from '@/api/generated/@tanstack/react-query.gen'
import { cn } from '@/lib/utils'

// Mapping backend CheckpointCategory enum variants to high-contrast Neo-brutalist badge colors
const CATEGORY_COLORS: Record<string, string> = {
    subject: 'bg-blue-400 text-black',
    nation: 'bg-pink-400 text-black',
    hobby: 'bg-emerald-400 text-black',
    hyy: 'bg-amber-400 text-black',
    yliopisto: 'bg-purple-400 text-black',
    other: 'bg-blush-pop-400 text-black',
    default: 'bg-zinc-200 text-black',
}

export function CheckpointList() {
    const [selectedId, setSelectedId] = React.useState<string | null>(null)
    const [searchQuery, setSearchQuery] = React.useState('')
    const [categoryFilter, setCategoryFilter] = React.useState<string>('all')

    // Fetch checkpoints using autogenerated TanStack Query options
    const {
        data: checkpoints = [],
        isLoading,
        isError,
        error,
        refetch,
        isRefetching,
    } = useQuery(listCheckpointsOptions())

    // Safely filter checkpoints by search query and category
    const filteredCheckpoints = React.useMemo(() => {
        const q = searchQuery.trim().toLowerCase()

        return checkpoints.filter((cp) => {
            // 1. Category Filter Check
            const matchesCategory =
                categoryFilter === 'all' || cp.category === categoryFilter

            if (!matchesCategory) return false

            // 2. Search Query Matching (if query is empty, return all matching category)
            if (!q) return true

            const nameMatch = cp.name ? cp.name.toLowerCase().includes(q) : false
            const locationMatch = cp.location_name
                ? cp.location_name.toLowerCase().includes(q)
                : false
            const numberMatch = cp.number !== null && cp.number !== undefined
                ? String(cp.number).includes(q)
                : false
            const categoryMatch = cp.category ? cp.category.toLowerCase().includes(q) : false

            const descriptionMatch = cp.checkpoint_description
                ? (typeof cp.checkpoint_description === 'string'
                    ? cp.checkpoint_description
                    : JSON.stringify(cp.checkpoint_description)
                ).toLowerCase().includes(q)
                : false

            return (
                nameMatch ||
                locationMatch ||
                numberMatch ||
                categoryMatch ||
                descriptionMatch
            )
        })
    }, [checkpoints, searchQuery, categoryFilter])

    return (
        <div className="flex h-full min-h-[600px] w-full max-w-2xl flex-col overflow-hidden rounded-xl border-2 border-black bg-white shadow-xl isolate">
            {/* Header Bar */}
            <div className="flex flex-col gap-3 border-b-2 border-black bg-white p-4 shrink-0">
                <div className="flex items-center justify-between">
                    <div>
                        <h3 className="text-base font-extrabold uppercase tracking-tight text-black">
                            Checkpoints ({filteredCheckpoints.length})
                        </h3>
                        <p className="mt-0.5 text-xs font-medium text-black/70">
                            Browse event checkpoints, map coordinates, and placement details.
                        </p>
                    </div>

                    <div className="flex items-center gap-2">
                        <button
                            type="button"
                            onClick={() => refetch()}
                            disabled={isRefetching || isLoading}
                            className="flex items-center gap-1.5 rounded-md border-2 border-black bg-white px-2.5 py-1 text-xs font-extrabold text-black shadow-2xs transition-colors hover:bg-black/5 disabled:opacity-50"
                        >
                            <RefreshCw className={cn('h-3.5 w-3.5', isRefetching && 'animate-spin')} />
                            Refresh
                        </button>
                    </div>
                </div>

                {/* Filter & Search Bar */}
                <div className="flex flex-wrap items-center gap-2 pt-1">
                    <div className="relative flex-1 min-w-[200px]">
                        <Search className="absolute left-3 top-1/2 h-3.5 w-3.5 -translate-y-1/2 text-black/50" />
                        <input
                            type="text"
                            placeholder="Search by name or location..."
                            value={searchQuery}
                            onChange={(e) => setSearchQuery(e.target.value)}
                            className="w-full rounded-md border-2 border-black bg-white py-1.5 pl-8 pr-3 text-xs font-bold text-black placeholder:text-black/40 focus:outline-none focus:ring-2 focus:ring-black/20"
                        />
                    </div>

                    <select
                        value={categoryFilter}
                        onChange={(e) => setCategoryFilter(e.target.value)}
                        className="rounded-md border-2 border-black bg-white px-3 py-1.5 text-xs font-bold text-black focus:outline-none focus:ring-2 focus:ring-black/20"
                    >
                        <option value="all">All Categories</option>
                        <option value="subject">Subject</option>
                        <option value="nation">Nation</option>
                        <option value="hobby">Hobby</option>
                        <option value="hyy">HYY</option>
                        <option value="yliopisto">Yliopisto</option>
                        <option value="other">Other</option>
                    </select>
                </div>
            </div>

            {/* Content Area */}
            <div className="flex-1 overflow-y-auto min-h-0 bg-white">
                {/* Loading State */}
                {isLoading && (
                    <div className="flex flex-col items-center justify-center p-12 text-center">
                        <RefreshCw className="h-8 w-8 animate-spin text-black" />
                        <p className="mt-3 text-sm font-bold text-black uppercase tracking-wide">
                            Loading Checkpoints...
                        </p>
                    </div>
                )}

                {/* Error State */}
                {isError && (
                    <div className="m-4 flex items-center gap-3 rounded-md border-2 border-black bg-rose-100 p-4 text-xs font-bold text-black shadow-2xs">
                        <AlertCircle className="h-5 w-5 shrink-0 text-rose-600 stroke-[2.5]" />
                        <div>
                            <p className="font-extrabold uppercase">Failed to load checkpoints</p>
                            <p className="text-black/70 mt-0.5">{error?.message || 'An unexpected server error occurred.'}</p>
                        </div>
                    </div>
                )}

                {/* Empty State */}
                {!isLoading && !isError && filteredCheckpoints.length === 0 && (
                    <div className="flex flex-col items-center justify-center p-12 text-center">
                        <AlertCircle className="h-8 w-8 text-black/30" />
                        <p className="mt-2 text-sm font-bold text-black">No checkpoints found</p>
                        <p className="text-xs font-medium text-black/60">
                            Try adjusting your search query or category filter.
                        </p>
                    </div>
                )}

                {/* List items */}
                {!isLoading &&
                    !isError &&
                    filteredCheckpoints.map((cp, idx) => {
                        const hasLocation =
                            typeof cp.latitude === 'number' &&
                            typeof cp.longitude === 'number' &&
                            (cp.latitude !== 0 || cp.longitude !== 0)
                        const isSelected = selectedId === cp.id

                        const categoryKey =
                            cp.category && CATEGORY_COLORS[cp.category]
                                ? cp.category
                                : 'default'
                        const badgeColorClass = CATEGORY_COLORS[categoryKey]

                        return (
                            <React.Fragment key={cp.id}>
                                <div
                                    onClick={() => setSelectedId(isSelected ? null : cp.id)}
                                    className={cn(
                                        'flex flex-col gap-2.5 p-4 cursor-pointer transition-colors bg-white',
                                        isSelected ? 'bg-amber-50/80' : 'hover:bg-black/5'
                                    )}
                                >
                                    {/* Header Row */}
                                    <div className="flex items-start justify-between gap-2">
                                        <div className="flex items-center gap-2.5 min-w-0">
                                            <span
                                                className={cn(
                                                    'flex h-7 w-7 shrink-0 items-center justify-center rounded-full border border-black text-xs font-bold shadow-2xs [&>svg]:h-3.5 [&>svg]:w-3.5',
                                                    badgeColorClass
                                                )}
                                            >
                                                {cp.number ?? '•'}
                                            </span>

                                            <div className="flex flex-col min-w-0">
                                                <div className="flex items-center gap-2">
                                                    <span className="font-bold text-sm text-black leading-tight truncate">
                                                        {cp.name}
                                                    </span>
                                                    {cp.cancelled && (
                                                        <span className="text-[10px] font-black uppercase tracking-wider text-white bg-rose-600 px-1.5 py-0.2 rounded border border-black">
                                                            Cancelled
                                                        </span>
                                                    )}
                                                </div>

                                                {cp.category && (
                                                    <span className="mt-0.5 text-[10px] uppercase tracking-wider font-extrabold text-black/60">
                                                        {cp.category}
                                                    </span>
                                                )}
                                            </div>
                                        </div>

                                        <div className="flex items-center gap-1.5 shrink-0">
                                            {hasLocation ? (
                                                <span className="flex items-center text-[10px] font-bold text-black bg-emerald-300 px-2 py-0.5 rounded border border-black">
                                                    <Check className="mr-1 h-3 w-3 stroke-[3]" /> Placed
                                                </span>
                                            ) : (
                                                <span className="flex items-center text-[10px] font-bold text-black bg-amber-300 px-2 py-0.5 rounded border border-black">
                                                    <AlertCircle className="mr-1 h-3 w-3 stroke-[3]" /> Unset
                                                </span>
                                            )}

                                            {isSelected ? (
                                                <ChevronUp className="h-4 w-4 text-black" />
                                            ) : (
                                                <ChevronDown className="h-4 w-4 text-black/40" />
                                            )}
                                        </div>
                                    </div>

                                    {/* Expanded Details Body */}
                                    {isSelected && (
                                        <div className="flex flex-col gap-2.5 pt-2 border-t border-black/10 text-xs">
                                            {cp.location_name && (
                                                <div className="flex items-center gap-1.5 font-bold text-black/80">
                                                    <MapPin className="h-3.5 w-3.5 text-black shrink-0" />
                                                    <span>{cp.location_name}</span>
                                                </div>
                                            )}

                                            {cp.checkpoint_description ? (
                                                <p className="text-black/80 font-medium leading-relaxed whitespace-pre-line">
                                                    {String(cp.checkpoint_description)}
                                                </p>
                                            ) : (
                                                <p className="text-black/40 italic text-[11px]">
                                                    No description provided.
                                                </p>
                                            )}

                                            {hasLocation && (
                                                <div className="flex flex-wrap items-center justify-between gap-2">
                                                    <div className="flex items-center gap-3 text-[11px] font-mono font-bold text-black/70 bg-black/5 p-1.5 rounded border border-black/10">
                                                        <span>Lat: {cp.latitude?.toFixed(5)}</span>
                                                        <span>Lng: {cp.longitude?.toFixed(5)}</span>
                                                        {cp.lanes && <span>Lanes: {cp.lanes}</span>}
                                                        {cp.accessible && (
                                                            <span className="text-emerald-700 font-extrabold">Accessible</span>
                                                        )}
                                                    </div>

                                                    {/* Edit Button */}
                                                    <Link
                                                        to="/checkpoints/$id"
                                                        params={{ id: cp.id }}
                                                        onClick={(e) => e.stopPropagation()}
                                                        className="flex items-center gap-1 rounded-md border-2 border-black bg-amber-400 px-3 py-1 text-xs font-black text-black shadow-2xs hover:bg-amber-300 transition-colors"
                                                    >
                                                        <Edit3 className="h-3.5 w-3.5" />
                                                        Edit Checkpoint
                                                    </Link>
                                                </div>
                                            )}

                                            {!hasLocation && (
                                                <div className="flex justify-end pt-1">
                                                    <Link
                                                        to="/checkpoints/$id"
                                                        params={{ id: cp.id }}
                                                        onClick={(e) => e.stopPropagation()}
                                                        className="flex items-center gap-1 rounded-md border-2 border-black bg-amber-400 px-3 py-1 text-xs font-black text-black shadow-2xs hover:bg-amber-300 transition-colors"
                                                    >
                                                        <Edit3 className="h-3.5 w-3.5" />
                                                        Edit Checkpoint
                                                    </Link>
                                                </div>
                                            )}
                                        </div>
                                    )}
                                </div>

                                {/* Inset dividing border */}
                                {idx < filteredCheckpoints.length - 1 && (
                                    <div className="mx-4 border-b border-black/20" />
                                )}
                            </React.Fragment>
                        )
                    })}
            </div>
        </div>
    )
}
